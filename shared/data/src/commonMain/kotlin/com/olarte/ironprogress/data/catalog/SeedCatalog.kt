    private fun seed(
        id: String,
        es: String,
        en: String,
        trackingType: TrackingType = TrackingType.WEIGHT_REPS,
        equipment: Equipment,
        pattern: MovementPattern,
        primary: List<Muscle>,
        secondary: List<Muscle> = emptyList(),
        unilateral: Boolean = false,
    ): Exercise = Exercise(
        id = ExerciseId(id),
        name = LocalizedText(es = es, en = en),
        trackingType = trackingType,
        equipment = equipment,
        pattern = pattern,
        muscles = primary.map { ExerciseMuscle(it, MuscleRole.PRIMARY) } +
            secondary.map { ExerciseMuscle(it, MuscleRole.SECONDARY) },
        unilateral = unilateral,
    )
